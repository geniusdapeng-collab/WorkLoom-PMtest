import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { countDeepSeekInputTokens, DEEPSEEK_V41_WINDOW, encodeDeepSeekRequest, planDeepSeekWindow } from "./deepseek-window.js";

interface Golden { id: string; body: Record<string, unknown>; officialPrompt: string; officialTokenIds: number[]; officialInputTokens: number }
const goldens: { recipeVersion: string; tokenizerSha256: string; caseCount: number; cases: Golden[] } = JSON.parse(readFileSync(
  new URL("./fixtures/deepseek-v41-recipe-0.2.0.json", import.meta.url), "utf8"));
const request = (text: string): Record<string, unknown> => ({ model: "deepseek-flash", thinking: { type: "disabled" }, messages: [{ role: "user", content: text }] });

describe("DeepSeek official V4.1 tokenizer and complete request rendering", () => {
  it("uses the exact licensed tokenizer asset, rather than an estimated character ratio", () => {
    const bytes = readFileSync(new URL("./assets/deepseek-v41/tokenizer.json", import.meta.url));
    expect(createHash("sha256").update(bytes).digest("hex")).toBe(DEEPSEEK_V41_WINDOW.tokenizerSha256);
    expect(goldens.tokenizerSha256).toBe(DEEPSEEK_V41_WINDOW.tokenizerSha256);
    expect(goldens.recipeVersion).toBe(DEEPSEEK_V41_WINDOW.recipeVersion);
    expect(goldens.caseCount).toBe(goldens.cases.length);
    expect(new Set(goldens.cases.map((row) => row.id)).size).toBe(goldens.cases.length);
    expect(readFileSync(new URL("./assets/deepseek-v41/LICENSE-TOKENIZER.txt", import.meta.url), "utf8")).toContain("Copyright (c) 2023 DeepSeek");
    expect(readFileSync(new URL("./assets/deepseek-v41/LICENSE-RECIPE.txt", import.meta.url), "utf8")).toContain("Copyright (c) 2026 DeepSeek");
  });

  it.each(goldens.cases)("$id matches every token ID independently generated by official Python", async (golden) => {
    const actual = await encodeDeepSeekRequest(golden.body);
    expect(actual.prompt).toBe(golden.officialPrompt);
    expect(actual.tokenIds).toEqual(golden.officialTokenIds);
    expect(actual.tokenIds.length).toBe(golden.officialInputTokens);
    expect(await countDeepSeekInputTokens(golden.body)).toBe(golden.officialInputTokens);
  });

  it("includes tools, response schema, reasoning and tool results in the actual complete prompt", async () => {
    const full = goldens.cases.find((row) => row.id === "combined-tools-json-schema")!;
    const measured = await encodeDeepSeekRequest(full.body);
    const plain = await countDeepSeekInputTokens(request("检索资料 JSON"));
    expect(measured.tokenIds.length).toBeGreaterThan(plain + 200);
    expect(measured.prompt).toContain("### Available Tool Schemas");
    expect(measured.prompt).toContain("## Response Format:");
    expect(measured.prompt).toContain("tool reasoning");
    expect(measured.prompt).toContain("<tool_result>命中结果</tool_result>");
  });

  it("takes a wire snapshot and returns the exact body/hash to send with maximum legal output", async () => {
    const original = goldens.cases.find((row) => row.id === "combined-tools-json-schema")!.body;
    const before = JSON.stringify(original);
    const plan = await planDeepSeekWindow(original);
    expect(plan.fullInputTokens).toBe(goldens.cases.find((row) => row.id === "combined-tools-json-schema")!.officialInputTokens);
    expect(plan.maxOutputTokens).toBe(393216);
    expect(plan.body).toEqual({ ...original, max_tokens: 393216 });
    expect(JSON.parse(plan.serializedBody)).toEqual(plan.body);
    expect(plan.requestSha256).toBe(createHash("sha256").update(plan.serializedBody).digest("hex"));
    expect(JSON.stringify(original)).toBe(before);
    expect(plan.body).not.toBe(original);
    expect(plan.body.messages).not.toBe(original.messages);
    expect(plan.recipeCommit).toBe(DEEPSEEK_V41_WINDOW.recipeCommit);
  });

  it("does not preserve an accidental small max_tokens as model capacity", async () => {
    const plan = await planDeepSeekWindow({ ...request("Hello"), max_tokens: 4096 });
    expect(plan.fullInputTokens).toBe(5);
    expect(plan.maxOutputTokens).toBe(393216);
    expect(JSON.parse(plan.serializedBody).max_tokens).toBe(393216);
  });

  it("counts the real full window at its output-cap transition and one-token/zero-token edges", { timeout: 60000 }, async () => {
    // Each additional 'a ' adds exactly one official BPE token; confirm the
    // invariant with the independently pinned engine before constructing edges.
    const overhead = await countDeepSeekInputTokens(request("a ")) - 1;
    expect(await countDeepSeekInputTokens(request("a ".repeat(37)))).toBe(overhead + 37);
    const make = (tokens: number) => request("a ".repeat(tokens - overhead));
    const transition = DEEPSEEK_V41_WINDOW.contextTokens - DEEPSEEK_V41_WINDOW.maxOutputTokens + 1;
    const limited = await planDeepSeekWindow(make(transition));
    expect(limited.fullInputTokens).toBe(transition);
    expect(limited.maxOutputTokens).toBe(393215);
    const last = await planDeepSeekWindow(make(DEEPSEEK_V41_WINDOW.contextTokens - 1));
    expect(last.fullInputTokens).toBe(1048575);
    expect(last.maxOutputTokens).toBe(1);
    await expect(planDeepSeekWindow(make(DEEPSEEK_V41_WINDOW.contextTokens))).rejects.toMatchObject({ code: "DEEPSEEK_WINDOW_EXHAUSTED" });
    await expect(planDeepSeekWindow(make(DEEPSEEK_V41_WINDOW.contextTokens + 1))).rejects.toMatchObject({ code: "DEEPSEEK_WINDOW_EXHAUSTED" });
  });

  it.each(["image_url", "file", "input_audio", "video"])("rejects uncounted %s parts before dispatch", async (type) => {
    await expect(planDeepSeekWindow({ ...request("unused"), messages: [{ role: "user", content: [{ type, image_url: { url: "https://example.invalid/sensitive" } }] }] }))
      .rejects.toMatchObject({ code: "DEEPSEEK_WINDOW_UNSUPPORTED" });
  });

  it.each(["deepseek-chat", "DeepSeek-V4.1-Flash", "deepseek-unknown", "other-model"])("does not guess an unregistered model %s", async (model) => {
    await expect(planDeepSeekWindow({ ...request("hello"), model })).rejects.toMatchObject({ code: "DEEPSEEK_WINDOW_UNSUPPORTED" });
  });

  it("fails closed on unknown prompt-affecting fields, malformed roles and missing tool results", async () => {
    await expect(planDeepSeekWindow({ ...request("hello"), instructions: "hidden input" })).rejects.toMatchObject({ code: "DEEPSEEK_WINDOW_UNSUPPORTED" });
    await expect(planDeepSeekWindow({ ...request("hello"), messages: [{ role: "developer", content: "hidden" }] })).rejects.toMatchObject({ code: "DEEPSEEK_WINDOW_UNSUPPORTED" });
    await expect(planDeepSeekWindow({ ...request("hello"), messages: [{ role: "tool", tool_call_id: "orphan", content: "result" }] })).rejects.toMatchObject({ code: "DEEPSEEK_WINDOW_PROTOCOL" });
    await expect(planDeepSeekWindow({ ...request("hello"), messages: [{ role: "assistant", tool_calls: [{ id: "c", type: "function", function: { name: "f", arguments: "{}" } }] }] }))
      .rejects.toMatchObject({ code: "DEEPSEEK_WINDOW_PROTOCOL" });
    await expect(planDeepSeekWindow(request("bad\ud800"))).rejects.toMatchObject({ code: "DEEPSEEK_WINDOW_PROTOCOL" });
  });

  it("does not silently approximate unsupported prefix/tool or JSON-mode combinations", async () => {
    const prefix = [{ role: "user", content: "hello" }, { role: "assistant", content: "answer", prefix: true }];
    const tools = [{ type: "function", function: { name: "f", parameters: { type: "object" } } }];
    await expect(planDeepSeekWindow({ ...request("unused"), messages: prefix, tools, tool_choice: "none" })).rejects.toMatchObject({ code: "DEEPSEEK_WINDOW_PROTOCOL" });
    await expect(planDeepSeekWindow({ ...request("hello"), response_format: { type: "json_object" } })).rejects.toMatchObject({ code: "DEEPSEEK_WINDOW_PROTOCOL" });
    await expect(planDeepSeekWindow({ ...request("hello"), thinking: { type: "enabled" }, tools, tool_choice: "required" })).rejects.toMatchObject({ code: "DEEPSEEK_WINDOW_PROTOCOL" });
  });
});
